let lang = 'bn';
try { lang = localStorage.getItem('la_lang') || 'bn'; } catch (e) {}

export function getLang() { return lang; }
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('la_lang', l); } catch (e) {}
  document.documentElement.lang = l;
}
export function s(key) { const v = STR[key]; return v ? (v[lang] || v.en) : key; }
export function tr(obj) { if (!obj) return ''; if (typeof obj === 'string') return obj; return obj[lang] || obj.en; }
export function num(n) {
  if (lang !== 'bn') return String(n);
  return String(n).replace(/[0-9]/g, d => '০১২৩৪৫৬৭৮৯'[d]);
}
